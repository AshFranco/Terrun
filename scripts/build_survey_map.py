"""Build survey/map-data.js (streets of Piantini/Naco for the survey's demo map).

Input: an Overpass API JSON export with `out geom` for the bbox
(18.455,-69.960,18.495,-69.915), containing:
  way["highway"~"^(trunk|primary|secondary|tertiary|unclassified|residential)$"]
  node["place"="neighbourhood"]

Usage:
  python3 scripts/build_survey_map.py path/to/overpass.json

Streets and neighbourhood names (c) OpenStreetMap contributors, ODbL.
"""
import json
import sys
from pathlib import Path

VIEW = (18.4595, -69.9490, 18.4845, -69.9330)  # south, west, north, east
MARGIN = 0.002
MAJOR = {"trunk", "primary", "secondary"}
OUT = Path(__file__).resolve().parent.parent / "survey" / "map-data.js"


def inside(lat, lon, pad=MARGIN):
    s, w, n, e = VIEW
    return s - pad <= lat <= n + pad and w - pad <= lon <= e + pad


def main(src):
    els = json.loads(Path(src).read_text())["elements"]
    ways = [e for e in els if e["type"] == "way"]

    streets = []
    for e in ways:
        pts = e["geometry"]
        if not any(inside(p["lat"], p["lon"]) for p in pts):
            continue
        hw = e.get("tags", {}).get("highway")
        cls = 0 if hw in MAJOR else (1 if hw == "tertiary" else 2)
        flat = []
        for p in pts:
            flat += [round(p["lat"], 5), round(p["lon"], 5)]
        streets.append([cls] + flat)

    def named(fragment):
        return [p for e in ways if fragment in e.get("tags", {}).get("name", "") for p in e["geometry"]]

    # Churchill as one centerline: average the dual carriageway per latitude bin.
    bins = {}
    for p in named("Winston Churchill"):
        bins.setdefault(round(p["lat"] / 0.0003), []).append(p)
    churchill = [[round(sum(p["lat"] for p in b) / len(b), 5), round(sum(p["lon"] for p in b) / len(b), 5)]
                 for _, b in sorted(bins.items())]

    best = None
    for p in named("Winston Churchill"):
        for q in named("Mejía Ricart"):
            d = (p["lat"] - q["lat"]) ** 2 + (p["lon"] - q["lon"]) ** 2
            if best is None or d < best[0]:
                best = (d, p)
    cross = [round(best[1]["lat"], 5), round(best[1]["lon"], 5)]

    places = [[e["tags"]["name"], round(e["lat"], 5), round(e["lon"], 5)]
              for e in els if e["type"] == "node" and inside(e["lat"], e["lon"], 0.006)]

    payload = {"view": VIEW, "streets": streets, "churchill": churchill, "cross": cross, "places": places}
    body = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    OUT.write_text("// Generated by scripts/build_survey_map.py. Streets (c) OpenStreetMap contributors, ODbL.\n"
                   f"window.TERRUN_MAP = {body};\n")
    print(f"{OUT} {OUT.stat().st_size / 1024:.0f} KB, streets={len(streets)}, places={len(places)}, "
          f"churchill={len(churchill)} pts, cross={cross}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
